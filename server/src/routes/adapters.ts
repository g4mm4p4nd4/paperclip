// ---------------------------------------------------------------------------
// Request / Response types
// ---------------------------------------------------------------------------

interface AdapterInstallRequest {
  /** npm package name (e.g., "droid-paperclip-adapter") or local path */
  packageName: string;
  /** True if packageName is a local filesystem path */
  isLocalPath?: boolean;
  /** Target version for npm packages (optional, defaults to latest) */
  version?: string;
  /** Explicit immutable installation authority; never treated as a local path. */
  installKind?: "npm" | "local_path" | "managed_immutable_bundle";
  /** Absolute content-addressed receipt generated by the adapter bundle builder. */
  installReceiptPath?: string;
  /** Exact operator-approved receipt digest. */
  installReceiptSha256?: string;
  /** Optimistic-lock identity. Null/omitted means the managed slot must be empty. */
  expectedCurrentBundleSha256?: string | null;
}

interface AdapterInfo {
  type: string;
  label: string;
  source: "builtin" | "external";
  modelsCount: number;
  loaded: boolean;
  disabled: boolean;
  /** True when an external plugin has replaced a built-in adapter of the same type. */
  overriddenBuiltin?: boolean;
  /** True when the external override for a builtin type is currently paused. */
  overridePaused?: boolean;
  version?: string;
  packageName?: string;
  isLocalPath?: boolean;
  installKind?: "npm" | "local_path" | "managed_immutable_bundle";
  bundleSha256?: string;
  manifestSha256?: string;
  installReceiptSha256?: string;
  /** Server-derived capability; never inferred from client session shape. */
  canManageManagedRuntime?: boolean;
  rollbackTargets?: Array<{
    bundleSha256: string;
    packageVersion: string;
    manifestSha256: string;
  }>;
}

